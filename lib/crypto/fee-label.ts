// lib/crypto/fee-label.ts
//
// Рядок комісії ескроу за ставкою з контракту (базисні пункти). Нуль це не помилка: за замовчуванням контракт
// розгортається без комісії, тож пишемо «Комісія: немає», а не «0%».

export const feeLabel = (feeBps: number | null): string => {
  if (feeBps === null) return "Комісія: читаємо з контракту…";
  return feeBps === 0 ? "Комісія: немає" : `Комісія, ${feeBps / 100}%`;
};
