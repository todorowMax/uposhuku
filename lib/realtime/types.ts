// lib/realtime/types.ts
//
// Події реального часу. Несут только «что изменилось», без данных: клиент
// перечитывает нужное обычным API, так права доступа проверяются там, а не тут.

export type RealtimeEvent =
  /** У розмові з'явилось повідомлення (або сама розмова). */
  | { t: "message"; conversationId: string }
  /** Угода змінилась: у другої сторони її треба перечитати. */
  | { t: "deal"; requestId: string }
  /** На мій запит прийшов відгук (або його відкликали). */
  | { t: "offer"; requestId: string }
  /** Публічне: з'явився чи закрився запит. */
  | { t: "feed" }
  /** Публічне: на карті змінились виконавці. */
  | { t: "map" };

export type RealtimeType = RealtimeEvent["t"];
