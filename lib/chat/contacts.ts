// lib/chat/contacts.ts
//
// Контакти поза чатом не блокуємо, а попереджаємо (вирішено в плані): номер
// телефону, @нік, посилання на месенджери.

export const mentionsContacts = (text: string) =>
  /(\+?\d[\d\s\-()]{8,}\d)|(^|\s)@[a-z0-9_]{4,}|t\.me\/|wa\.me\/|viber|telegram|телеграм|вайбер|whatsapp|ватсап/i.test(text);

/**
 * Текст без контактів: телефони, пошта, @ніки й посилання замінюємо на
 * «[контакт приховано]». Для публічних місць (канал, сповіщення), де
 * відгукнутися можна лише на платформі.
 */
export const stripContacts = (text: string): string =>
  text
    .replace(/(?:https?:\/\/|www\.|t\.me\/|wa\.me\/)\S+/gi, "[контакт приховано]")
    .replace(/\S+@\S+\.\S+/g, "[контакт приховано]")
    .replace(/(^|\s)@[A-Za-z0-9_]{4,}/g, "$1[контакт приховано]")
    .replace(/\+?\d[\d\s\-()]{8,}\d/g, "[контакт приховано]");
